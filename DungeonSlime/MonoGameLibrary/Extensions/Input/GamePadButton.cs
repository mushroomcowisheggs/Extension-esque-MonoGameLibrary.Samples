namespace MonoGameLibrary.Extensions.Input {
    /// <summary>
    /// Represents buttons on a gamepad.
    /// </summary>
    public enum GamePadButton {
        /// <summary>A button (bottom).</summary>
        A,
        /// <summary>B button (right).</summary>
        B,
        /// <summary>X button (top).</summary>
        X,
        /// <summary>Y button (left).</summary>
        Y,
        
        /// <summary>Start button.</summary>
        Start,
        /// <summary>Back button.</summary>
        Back,
        
        /// <summary>Left stick pressed.</summary>
        LeftStick,
        /// <summary>Right stick pressed.</summary>
        RightStick,
        
        /// <summary>Left shoulder/bumper.</summary>
        LeftShoulder,
        /// <summary>Right shoulder/bumper.</summary>
        RightShoulder,
        
        /// <summary>D‑pad up.</summary>
        DPadUp,
        /// <summary>D‑pad down.</summary>
        DPadDown,
        /// <summary>D‑pad left.</summary>
        DPadLeft,
        /// <summary>D‑pad right.</summary>
        DPadRight,
        
        /// <summary>Left thumbstick pushed upward past the dead zone.</summary>
        LeftThumbstickUp,
        /// <summary>Left thumbstick pushed downward past the dead zone.</summary>
        LeftThumbstickDown,
        /// <summary>Left thumbstick pushed leftward past the dead zone.</summary>
        LeftThumbstickLeft,
        /// <summary>Left thumbstick pushed rightward past the dead zone.</summary>
        LeftThumbstickRight,
        
        /// <summary>Right thumbstick pushed upward past the dead zone.</summary>
        RightThumbstickUp,
        /// <summary>Right thumbstick pushed downward past the dead zone.</summary>
        RightThumbstickDown,
        /// <summary>Right thumbstick pushed leftward past the dead zone.</summary>
        RightThumbstickLeft,
        /// <summary>Right thumbstick pushed rightward past the dead zone.</summary>
        RightThumbstickRight,
    }
}